def _read_text(path, cap=None):
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return ""
    if cap and len(text) > cap:
        half = cap // 2
        return text[:half] + "\n[... middle omitted ...]\n" + text[-half:]
    return text


def _lab_keys(lab_display):
    clean = re.sub(r"^\[.*?\]\s*", "", lab_display)
    head = clean.split(" / ")[0].lower().replace(" ", "")
    sub = clean.split(" / ")[1].lower().replace(" ", "") if " / " in clean else ""
    return head, sub


def _resolve_module_key(module):
    """Normalize a module value to a canonical course key."""
    key = str(module or "").strip().upper()
    return MODULE_KEY_ALIASES.get(key, key)


def module_for_lab_display(lab_display):
    """Course key for a lab display string.

    Lab display strings carry their course in a bracket prefix (e.g.
    "[ATPG Core] Lab4 / EX2"), see agents.deep_study_agent.list_lab_exercises().
    The "ATPG Core" course spans two canonical domains, so it is resolved per
    lab: Labs 2 and 3 are SCAN, the remaining ATPG Core labs are ATPG.
    """
    text = str(lab_display or "")
    m = re.match(r"^\[(.*?)\]", text)
    prefix = m.group(1) if m else ""
    if prefix == "ATPG Core":
        clean = re.sub(r"^\[.*?\]\s*", "", text)
        head, _sub = _lab_keys(clean)
        lab_m = re.match(r"^lab(\d+)$", head)
        if lab_m and lab_m.group(1) in ATPG_CORE_SCAN_LAB_NUMBERS:
            return "SCAN"
        return "ATPG"
    return COURSE_PREFIX_MODULES.get(prefix, DEFAULT_MODULE)


def _split_pages(text):
    """Splits ingest text into (label, body) tuples at [SOURCE: ...] markers."""
    pages = []
    marker = "[SOURCE:"
    idx = text.find(marker)
    while idx != -1:
        end = text.find("]", idx)
        nxt = text.find(marker, idx + 1)
        if end == -1:
            end = idx + 10
        label = text[idx + 1:end].strip()
        body = text[end + 1:nxt if nxt != -1 else len(text)]
        pages.append((label, body.strip()))
        idx = nxt
    return pages


def _lab_scope_text(lab_display):
    """Lab-slides OCR pages that belong to this lab exercise."""
    clean = re.sub(r"^\[.*?\]\s*", "", lab_display)
    head, sub = _lab_keys(clean)
    _warm_page_cache()
    picked = []
    for label, body in _page_body_cache.items():
        blob = (label + "\n" + body).lower().replace(" ", "")
        if (head and head in blob) or (sub and sub in blob):
            picked.append(body)
    return "\n\n".join(picked)


def _lab_folder_text(lab_display):
    """Concatenated TCL/text file contents inside the lab folder on disk."""
    clean = re.sub(r"^\[.*?\]\s*", "", lab_display)
    target = LAB_DIR / clean.replace(" / ", "/")
    if not target.exists():
        return ""
    if target.is_file():
        return _read_text(target, cap=60000)
    parts = []
    for p in sorted(target.rglob("*")):
        if p.is_file() and p.suffix.lower() in (".tcl", ".txt", ".do", ".f", ".sdc"):
            parts.append(_read_text(p, cap=30000))
    return "\n".join(parts)


def _lab_number(display):
    """('lab number', 'exercise number') parsed from a lab display string."""
    clean = re.sub(r"^\[.*?\]\s*", "", str(display or ""))
    head, sub = _lab_keys(clean)
    lab = re.match(r"lab(\d+)", head)
    exercise = re.match(r"exercise(\d+)", sub)
    return (lab.group(1) if lab else None, exercise.group(1) if exercise else None)


# A section heading line inside a workbook body. TOC lines are excluded later by
# rejecting headings that still carry dot leaders.
_SECTION_HEADING_RE = re.compile(
    r"(?im)^(?:lab\s+\d+|exercise\s+\d+|assessment\b|knowledge check\b)[^\n]*$"
)


def _section_range(workbook_text, lab_number, exercise_number=None):
    """Text of one exercise (or lab) section: heading through to the next heading.

    WP-6: the previous implementation selected *individual lines* containing
    "labN"/"exerciseN", which matched only TOC and page-header lines, so TestKompress,
    Tessent Shell and ATPG Advanced labs always yielded zero commands. Slicing a real
    section keeps every command in the exercise body inside the scope.
    """
    if not lab_number:
        return ""
    headings = [m for m in _SECTION_HEADING_RE.finditer(workbook_text) if "..." not in m.group(0)]
    lab_heads = [m for m in headings if re.match(r"(?i)lab\s+%s\b" % lab_number, m.group(0).strip())]
    if not lab_heads:
        return ""
    lab_start = lab_heads[0].start()

    if exercise_number:
        ex_heads = [
            m for m in headings
            if m.start() > lab_start and re.match(r"(?i)exercise\s+%s\b" % exercise_number, m.group(0).strip())
        ]
        if ex_heads:
            start = ex_heads[0].start()
            following = [m for m in headings if m.start() > start]
            end = following[0].start() if following else len(workbook_text)
            return workbook_text[start:end]
        # The workbook uses exercise headings but not this one: the requested exercise
        # is absent, so abstain instead of mixing the whole lab section into it (the
        # original no-cross-contamination contract).
        if any(re.match(r"(?i)exercise\s+\d+\b", m.group(0).strip()) for m in headings):
            return ""

    following_labs = [
        m for m in headings
        if m.start() > lab_start and re.match(r"(?i)lab\s+\d+\b", m.group(0).strip())
    ]
    end = following_labs[0].start() if following_labs else len(workbook_text)
    return workbook_text[lab_start:end]


_KNOWN_CACHE = None


def _known_commands():
    """Command vocabulary for lab extraction.

    WP-6: the curated 44-command allowlist is extended with every command in the
    expanded WP-2 index, so a real documented command used in a lab body (for example
    ``create_tsdb``) is recognised instead of being dropped as unknown.
    """
    global _KNOWN_CACHE
    if _KNOWN_CACHE is None:
        names = set(KNOWN_COMMANDS)
        try:
            from core.command_indexer import load_command_index

            names |= set(load_command_index().get("commands", {}))
        except Exception:
            pass
        _KNOWN_CACHE = names
    return _KNOWN_CACHE


def extract_lab_commands(lab_display, module=None):
    """Ordered, deduped list of Tessent commands used in ONE lab exercise.

    Regex hits are filtered through KNOWN_COMMANDS to drop OCR fused-word
    artifacts (read_verilogdesign etc.); a substring pass then catches flow
    commands whose OCR text got mangled beyond the exact form.
    When module names a course that has a lab workbook (EDT, TSHELL_LINUX,
    ATPG_ADV) the exercise text is read from that workbook.  The ATPG Core
    course ("ATPG" / "SCAN") has no workbook entry: its labs are read from
    the lab slides OCR text and the on-disk lab folder.

    A lab that is not present in the corpus yields an empty list and a
    warning; the whole workbook is never scanned on a failed match, because
    that would report commands from unrelated lab sections as if they
    belonged to the requested lab.
    """
    module_key = _resolve_module_key(module)
    if module_key in MODULE_WORKBOOKS:
        wb_path = MODULE_WORKBOOKS[module_key]
        wb_text = _read_text(wb_path, cap=400000)
        # WP-6: scope by section range instead of matching individual lines.
        lab_number, exercise_number = _lab_number(lab_display)
        section = _section_range(wb_text, lab_number, exercise_number)
        if not section.strip():
            # The requested lab/exercise is not in this workbook. Scanning the whole
            # workbook would silently attribute unrelated sections' commands to it, so
            # abstain and name the reason (unchanged contract).
            warnings.warn(
                "Lab %r was not found in %s (course %r); no commands extracted."
                % (lab_display, wb_path.name, module_key),
                stacklevel=2,
            )
            return []
        blob = section.lower()
    else:
        scoped = _lab_scope_text(lab_display)
        folder_text = _lab_folder_text(lab_display)
        blob = (scoped + "\n" + folder_text).lower()

    known = _known_commands()
    found = []
    seen = set()
    for m in CMD_RE.finditer(blob):
        cmd = m.group(0).lower()
        if cmd in known and cmd not in seen:
            seen.add(cmd)
            found.append(cmd)
    for cmd in KNOWN_COMMANDS:
        if cmd not in seen and cmd in blob:
            seen.add(cmd)
            found.append(cmd)
    # Drop substring shadows: set_scan (shadowed by set_scan_insertion_options),
    # set_system, read_cell_lib, add_black_box, etc.
    found = [c for c in found if not any(o != c and o.startswith(c) for o in found)]
    return found


# Page-body cache so reverse lookups do not re-read the slides file per call.
_page_body_cache = {}


def _warm_page_cache():
    if not _page_body_cache and LAB_SLIDES_FILE.exists():
        for label, body in _split_pages(_read_text(LAB_SLIDES_FILE, cap=400000)):
            _page_body_cache[label] = body


def where_used(command):
    """Reverse lookup: which lab exercises (all four courses) use a command.

    WP-6: the previous version only searched the ATPG Core lab-slides OCR, so it could
    never report TestKompress, Tessent Shell or ATPG Advanced usage. Every lab exercise
    is now indexed from its own section text (workbook section range, or the slides +
    folder material for ATPG Core) and resolved at exercise level.
    """
    cmd = command.lower().strip()
    if not cmd:
        return []
    pattern = re.compile(r"\b" + re.escape(cmd) + r"\b")
    hits = []
    for label, blob in _lab_text_index().items():
        if pattern.search(blob) and label not in hits:
            hits.append(label)
    return hits


_lab_text_cache: dict = {}


def _where_used_label(lab_display):
    """'[ATPG Core] Lab2 / EX1' -> 'ATPG Core / Lab2 / EX1' (course-qualified)."""
    text = str(lab_display or "").strip()
    course = text.split("]", 1)[0].lstrip("[") if text.startswith("[") else ""
    rest = re.sub(r"^\[.*?\]\s*", "", text)
    rest = rest.split(":", 1)[0].strip()
    return f"{course} / {rest}" if course else rest


def _lab_text_index():
    """Searchable lab text per lab exercise, built once per process."""
    if _lab_text_cache:
        return _lab_text_cache

    from agents.deep_study_agent import list_lab_exercises

    for lab in list_lab_exercises():
        try:
            module_key = _resolve_module_key(module_for_lab_display(lab))
            if module_key in MODULE_WORKBOOKS:
                workbook = _read_text(MODULE_WORKBOOKS[module_key], cap=400000)
                text = _section_range(workbook, *_lab_number(lab))
            else:
                text = _lab_scope_text(lab) + "\n" + _lab_folder_text(lab)
        except Exception:
            text = ""
        _lab_text_cache[_where_used_label(lab)] = text.lower()
    return _lab_text_cache


