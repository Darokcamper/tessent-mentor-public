def related_theory_for_lab(lab_display, max_results=8):
    """Theory lessons that belong to the same course as this lab exercise.

    WP-6 requirement 8. The link is course membership, which is directly evidenced by
    the lab workbook and the video transcripts both belonging to that course. It is
    deliberately NOT presented as a command-level match.
    """
    course = course_for_lab(lab_display)
    if not course:
        return []
    from agents.deep_study_agent import list_video_lessons, list_video_modules

    rows = []
    for module_key, module_display in sorted(list_video_modules().items()):
        if course not in module_display:
            continue
        for lesson in list_video_lessons(module_key):
            rows.append(
                {
                    "course": course,
                    "module": module_display,
                    "lesson": lesson,
                    "evidence": "course membership (lab workbook and course transcripts)",
                }
            )
            if len(rows) >= max_results:
                return rows
    return rows


def related_labs_for_lesson(module_key, max_results=8):
    """Labs that belong to the same course as a video module (reciprocal link)."""
    from agents.deep_study_agent import list_lab_exercises, list_video_modules

    course = None
    for key, display in list_video_modules().items():
        if key == module_key:
            for name in _LAB_PREFIX_COURSE.values():
                if name in display:
                    course = name
                    break
            break
    if not course:
        return []
    return [
        {"course": course, "lab": lab, "evidence": "course membership"}
        for lab in list_lab_exercises()
        if course_for_lab(lab) == course
    ][:max_results]


def crossref_lab(lab_display, max_commands=60, module=None):
    """Full cross-reference rows for ONE lab exercise.

    Returns a list of dicts: command, manual_defs -> [{source, page, text}],
    used_in -> [lab/ex strings].
    """
    _warm_page_cache()
    commands = extract_lab_commands(lab_display, module=module)[:max_commands]
    rows = []
    for cmd in commands:
        rows.append({
            "command": cmd,
            "manual_defs": retrieve_command_definition(cmd),
            "used_in": where_used(cmd),
        })
    return rows


def _norm_lab_key(name):
    """Normalizes a lab display string for overlap comparison.

    Strips Deep Study bracket prefixes (e.g. '[TK] ') and lowercases so that
    'Lab2 / EX3' and '[TK] Lab2 / EX3' compare equal; falls back to the raw
    stripped string when no separator is present.
    """
    return re.sub(r"^\[.*?\]\s*", "", str(name or "")).strip().lower()


def related_labs_for_display(lab_display, commands=None, max_results=5):
    """Rank other lab exercises sharing commands with *lab_display*.

    Uses only verified corpus evidence: each candidate lab's shared commands
    must appear in reverse-lookup results from ``where_used``.  Candidates
    with no shared command are never emitted (they offer no traceable
    evidence to a learner).  Returns a list of dicts with keys:
    ``lab``, ``shared`` (sorted shared-command list), and ``count``.
    Ordered by descending shared-command count, then alphabetically.
    """
    own_key = _norm_lab_key(lab_display)
    if not own_key:
        return []
    if commands is None:
        commands = extract_lab_commands(lab_display)
    shared_map = {}
    for cmd in commands or []:
        for hit in where_used(cmd):
            key = _norm_lab_key(hit)
            if not key or key == own_key:
                continue
            entry = shared_map.setdefault(key, {"lab": hit, "shared": set()})
            entry["shared"].add(cmd)
    ranked = sorted(
        shared_map.values(),
        key=lambda e: (-len(e["shared"]), e["lab"]),
    )
    out = []
    for entry in ranked[:max_results]:
        out.append({
            "lab": entry["lab"],
            "shared": sorted(entry["shared"]),
            "count": len(entry["shared"]),
        })
    return out


# ---------------------------------------------------------------------------
# Stage 2.4 — Relationship Labeling Engine
# Approved types (PHASE_1_PLAN_APPROVED.md §9.1, §9.3 and
# PHASE_2_PREFLIGHT_REPORT.md §4 Stage 2.4): exactly three values.
#
# DIRECTLY OBSERVED: Both commands appear in the same lab file or slide OCR
#   text (confirmed by regex search in the scoped blob via
#   _cooccur_in_lab_text).  Evidence source = actual file path;
#   evidence location = lab display string.
#
# INFERRED: Commands associated via shared flow steps or common dofile
#   sequences WITHOUT direct text co-occurrence (preflight §4).
#   Requires actual dofile/flow-step sequence evidence — a dedicated file
#   (e.g. a .do script or workbook flow table) in which both commands appear
#   as ordered steps.  The current corpus contains no such files; therefore
#   INFERRED cannot be emitted automatically.  It remains reserved for future
#   corpus enrichment.
#
# VALIDATED: Requires corroboration across multiple workbook sections AND
#   official manual flows (preflight §4).  Also not emittable from the current
#   corpus.  Reserved for future enrichment.
#
# OMITTED (no dict appended) in all other cases:
#   - Either command has no manual definition block.
#   - lab_display not supplied (cannot perform text co-occurrence check).
#   - Text co-occurrence check performed but both commands not found in the
#     same scoped text blob.
#   - No shared lab at all.
#   Relationships are silently dropped rather than emitted with evidence that
#   cannot be traced to an authoritative source.
# ---------------------------------------------------------------------------

_VALID_TYPES = frozenset({"DIRECTLY OBSERVED", "INFERRED", "VALIDATED"})


class _LabTextContext:
    """Reusable corpus text for one lab exercise.

    The scoped slides OCR text and the lab folder text are the same for every
    command pair, but producing them is expensive: the folder text walks the
    lab directory tree and re-reads every TCL/txt/dofile in it, and the slides
    text rescans the OCR page cache.  Building the context once and reusing it
    turns a per-pair sequence of filesystem walks into a single one.

    Both blobs are built lazily, so the folder text is still only read when a
    pair is not already confirmed in the slides text.
    """

    def __init__(self, lab_display):
        self.lab_display = lab_display
        # Evidence path reported for pairs found in the lab folder files.
        self.folder_source = str(
            LAB_DIR / re.sub(r"^\[.*?\]\s*", "", lab_display).replace(" / ", "/")
        )
        self._slides_blob = None
        self._folder_blob = None
        self._slides_hits = {}
        self._folder_hits = {}

    def _contains(self, which, cmd):
        """Whole-word match of *cmd* in the given blob, memoized per command.

        Memoizing keeps the number of regex scans proportional to the number
        of commands rather than to the number of command pairs.
        """
        hits = self._slides_hits if which == "slides" else self._folder_hits
        if cmd not in hits:
            blob = self._slides_blob if which == "slides" else self._folder_blob
            hits[cmd] = bool(re.search(r"\b" + re.escape(cmd) + r"\b", blob))
        return hits[cmd]

    def in_slides(self, cmd):
        """True when *cmd* occurs as a whole word in the scoped slides OCR text."""
        if self._slides_blob is None:
            self._slides_blob = _lab_scope_text(self.lab_display).lower()
        return self._contains("slides", cmd)

    def in_folder(self, cmd):
        """True when *cmd* occurs as a whole word in the lab folder files."""
        if self._folder_blob is None:
            self._folder_blob = _lab_folder_text(self.lab_display).lower()
        return self._contains("folder", cmd)


def _cooccur_in_lab_text(lab_display, cmd_a, cmd_b, context=None):
    """Return (found: bool, source_path: str) if *cmd_a* and *cmd_b* appear in
    the same scoped text blob for *lab_display*.

    Searches the lab slides OCR text (via _lab_scope_text) and then the lab
    folder TCL/txt files (via _lab_folder_text).  Returns the first source
    in which both commands are found together, or (False, '') if not found.

    *context* is an optional _LabTextContext.  When supplied, the scoped
    slides text and the lab folder text are read once and reused for every
    pair; when omitted a throwaway context is built for this call alone.
    """
    ctx = context if context is not None else _LabTextContext(lab_display)

    # Try slides OCR first (canonical corpus source).
    if ctx.in_slides(cmd_a) and ctx.in_slides(cmd_b):
        return True, str(LAB_SLIDES_FILE)

    # Try lab folder files (TCL, dofiles, txt).
    if ctx.in_folder(cmd_a) and ctx.in_folder(cmd_b):
        return True, ctx.folder_source

    return False, ""


def build_relationships(rows, lab_display=None):
    """Build typed relationship objects for every command pair in *rows*.

    Each relationship dict conforms to PHASE_1_PLAN_APPROVED.md §9.3:
        source_entity, target_entity, type, evidence_source,
        evidence_location, description, validation_status

    Per PHASE_2_PREFLIGHT_REPORT.md §4:

    DIRECTLY OBSERVED (the only type currently emittable):
        Both commands are confirmed by regex in the same scoped lab text blob
        (slides OCR or lab folder files) when *lab_display* is provided.
        evidence_source = actual file path; evidence_location = lab_display.

    INFERRED (reserved — not emitted automatically):
        Requires shared flow steps or common dofile sequences.  The current
        corpus contains no dedicated dofile or flow-sequence files, so this
        type cannot be established deterministically.

    VALIDATED (reserved — not emitted automatically):
        Requires multiple workbook sections + official manual flow corroboration.

    OMITTED in all other cases:
        - Either command has no manual definition block.
        - lab_display is None (text co-occurrence cannot be checked).
        - Text co-occurrence search performed but not confirmed.
        - No shared lab at all.

    Parameters
    ----------
    rows : list[dict]
        Output of crossref_lab(); each dict must have keys:
        command, manual_defs, used_in.
    lab_display : str or None
        The lab display string (e.g. "Lab4 / EX2") used to scope the OCR
        text search.  **Required** to emit any relationship; when None every
        pair is omitted because no evidence check is possible.
    """
    if not rows:
        return []

    # Without lab_display there is no corpus text to search — nothing to emit.
    if lab_display is None:
        return []

    relationships = []
    commands = [r["command"] for r in rows]
    defs_map = {r["command"]: r["manual_defs"] for r in rows}

    # The scoped slides text and the lab folder text are identical for every
    # command pair, so build them once and reuse them for all pairs instead of
    # re-reading the lab folder from disk inside the inner loop.
    context = _LabTextContext(lab_display)

    for i, cmd_a in enumerate(commands):
        for cmd_b in commands[i + 1:]:
            if cmd_a == cmd_b:
                continue

            defs_a = defs_map.get(cmd_a, [])
            defs_b = defs_map.get(cmd_b, [])

            # OMIT: either command lacks a manual definition block.
            # Cannot trace the relationship to an authoritative source.
            if not defs_a or not defs_b:
                continue

            # Attempt actual text co-occurrence in the scoped lab corpus.
            found, text_source = _cooccur_in_lab_text(
                lab_display, cmd_a, cmd_b, context=context,
            )
            if not found:
                # OMIT: text co-occurrence not confirmed; INFERRED would require
                # dofile/flow-step evidence which is not in this corpus.
                continue

            assert "DIRECTLY OBSERVED" in _VALID_TYPES  # sanity

            relationships.append({
                "source_entity": cmd_a,
                "target_entity": cmd_b,
                "type": "DIRECTLY OBSERVED",
                "evidence_source": text_source,
                "evidence_location": lab_display,
                "description": (
                    "'%s' and '%s' both appear in the lab text of '%s'. "
                    "Text co-occurrence confirmed in: %s."
                    % (cmd_a, cmd_b, lab_display, text_source)
                ),
                "validation_status": "pending",
            })

    return relationships


def format_crossref_table(rows, lab_display=None):
    """Markdown table + per-command definition blocks + Stage 2.4 relationship table.

    Parameters
    ----------
    rows : list[dict]
        Output of crossref_lab().
    lab_display : str or None
        The lab display string (e.g. "Lab4 / EX2").  When supplied, text
        co-occurrence is verified against the actual lab OCR/TCL corpus to
        assign DIRECTLY OBSERVED relationships.  When None, only INFERRED
        relationships (with shared-lab-flow evidence) are emitted.
    """
    if not rows:
        return "No Tessent commands were found in this lab exercise's material."
    lines = ["## Lab <-> Manual Cross-Reference", ""]

    # ── Summary table (extended with Relationship Type column) ──────────────
    lines.append("| # | Command | Rel. Type | Evidence Location | Manual Def? | Also Used In |")
    lines.append("|---|---------|-----------|-------------------|-------------|--------------|")

    # Build a quick lookup: best relationship type per command
    relationships = build_relationships(rows, lab_display=lab_display)
    _rel_summary = {}  # cmd -> (best_type, evidence_location)
    _TYPE_RANK = {"VALIDATED": 0, "DIRECTLY OBSERVED": 1, "INFERRED": 2}
    for rel in relationships:
        for cmd in (rel["source_entity"], rel["target_entity"]):
            existing = _rel_summary.get(cmd)
            rank = _TYPE_RANK.get(rel["type"], 99)
            if existing is None or rank < _TYPE_RANK.get(existing[0], 99):
                _rel_summary[cmd] = (rel["type"], rel["evidence_location"])

    for i, r in enumerate(rows, 1):
        n = len(r["manual_defs"])
        def_flag = (str(n) + " block(s)") if n else "not found in manuals"
        used = ", ".join(r["used_in"][:4]) if r["used_in"] else "-"
        rel_info = _rel_summary.get(r["command"])
        rel_type_cell = rel_info[0] if rel_info else "—"
        ev_loc_cell = rel_info[1] if rel_info else "—"
        lines.append(
            "| %d | `%s` | %s | %s | %s | %s |"
            % (i, r["command"], rel_type_cell, ev_loc_cell, def_flag, used)
        )

    # ── Per-command definition blocks ────────────────────────────────────────
    for r in rows:
        if not r["manual_defs"]:
            continue
        lines.append("")
        lines.append("### `" + r["command"] + "`")
        for d in r["manual_defs"][:2]:
            cite = "%s, Page %s" % (d.get("source", "?"), d.get("page", "?"))
            lines.append("")
            lines.append("> [Source: %s]" % cite)
            lines.append(">")
            body = str(d.get("text", "")).strip()
            if len(body) > 1200:
                body = body[:1200] + " ..."
            for ln in body.split("\n"):
                lines.append("> " + ln)

    # ── Stage 2.4 Relationship table ─────────────────────────────────────────
    if relationships:
        lines.append("")
        lines.append("## Command Relationships (Stage 2.4)")
        lines.append("")
        lines.append("| Source | Target | Type | Evidence Source | Evidence Location | Status |")
        lines.append("|--------|--------|------|-----------------|-------------------|--------|")
        for rel in relationships:
            src_short = rel["evidence_source"]
            if src_short and len(src_short) > 40:
                src_short = "..." + src_short[-37:]
            lines.append(
                "| `%s` | `%s` | **%s** | %s | %s | %s |"
                % (
                    rel["source_entity"],
                    rel["target_entity"],
                    rel["type"],
                    src_short,
                    rel["evidence_location"],
                    rel["validation_status"],
                )
            )

    return "\n".join(lines)
